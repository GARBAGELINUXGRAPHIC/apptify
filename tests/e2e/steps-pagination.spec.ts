import { expect, test } from '@playwright/test'

for (const width of [320, 390, 768, 1440]) {
  test(`steps independent hit areas and buttons fit at ${width}px`, async ({ page }) => {
    await page.setViewportSize({ width, height: 900 })
    await page.goto('/components#apple-steps')
    const steps = page.locator('#apple-steps .apple-steps')
    const circles = steps.locator('button.apple-steps__number')
    const labels = steps.locator('button.apple-steps__label')
    await expect(circles).toHaveCount(3)
    const current = () => steps.locator('li[aria-current="step"]')
    await expect(current()).toContainText('确认信息')
    const first = await steps.locator('li').first().boundingBox()
    await page.mouse.move(first!.x + 1, first!.y + 22)
    await page.mouse.click(first!.x + 1, first!.y + 22)
    await expect(current()).toContainText('确认信息')
    await expect(steps.locator('.v-ripple__container')).toHaveCount(0)
    const gap = await steps.locator('li').first().boundingBox()
    await page.mouse.click(gap!.x + gap!.width / 2, gap!.y + 48)
    await expect(current()).toContainText('确认信息')
    await labels.nth(2).hover()
    await expect(labels.nth(2)).toHaveCSS('background-color', 'rgba(0, 0, 0, 0)')
    await labels.nth(2).click()
    await expect(current()).toContainText('完成')
    await expect(labels.nth(2).locator('.v-ripple__container')).toHaveCount(0)
    await circles.nth(0).hover()
    await expect.poll(() => circles.nth(0).evaluate(el => getComputedStyle(el).backgroundColor === getComputedStyle(el).borderColor)).toBe(true)
    for (const index of [0, 2, 1, 2, 0]) await circles.nth(index).click()
    await expect(current()).toContainText('选择产品')
    await labels.nth(1).focus()
    await page.keyboard.press('Enter')
    await expect(current()).toContainText('确认信息')
    await circles.nth(2).focus()
    await page.keyboard.press('Space')
    await expect(current()).toContainText('完成')
    await page.mouse.move(0, 0)
    const colors = await circles.nth(0).evaluate(el => ({background:getComputedStyle(el).backgroundColor, border:getComputedStyle(el).borderColor, radius:getComputedStyle(el).borderRadius}))
    expect(colors.background).not.toBe(colors.border)
    expect(colors.radius).toBe('50%')
    const bounds = await steps.boundingBox()
    expect(bounds!.x + bounds!.width).toBeLessThanOrEqual(width)
    expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBeLessThanOrEqual(width)
  })
}

for (const width of [320, 390, 768, 1440]) {
  test(`pagination manual draft, validation and joined controls fit at ${width}px`, async ({ page }) => {
    await page.setViewportSize({ width, height: 900 })
    await page.goto('/tests/e2e/fixtures/steps-pagination.html')
    const pagination = page.locator('#pagination')
    const input = pagination.getByRole('textbox', { name: '跳转页码' })
    const apply = pagination.getByRole('button', { name: 'Apply', exact: true })
    await input.fill('2')
    await expect(page.locator('#page')).toHaveText('12')
    await input.fill('24')
    await expect(page.locator('#commits')).toHaveText('0')
    await apply.click()
    await expect(page.locator('#page')).toHaveText('24')
    await input.fill('1.5')
    await input.press('Enter')
    await expect(input).toHaveValue('1.5')
    await expect(input).toHaveAttribute('aria-invalid', 'true')
    await expect(pagination.getByRole('alert')).toContainText('1–25')
    await expect(page.locator('#commits')).toHaveText('1')
    await input.fill('3')
    await input.press('Enter')
    await expect(page.locator('#page')).toHaveText('3')
    await expect(pagination.getByRole('alert')).toHaveCount(0)
    const shape = await input.evaluate(el => {
      const wrap = el.closest('.apple-input-wrap')!, button = wrap.querySelector('button')!
      const i = el.getBoundingClientRect(), b = button.getBoundingClientRect(), css = getComputedStyle(button)
      return { gap:b.left-i.right, left:css.borderTopLeftRadius, right:css.borderTopRightRadius, parent:getComputedStyle(wrap).borderRadius }
    })
    expect(Math.abs(shape.gap)).toBeLessThan(1)
    expect(shape.left).toBe('0px')
    expect(shape.right).toBe('7px')
    expect(shape.parent).toBe('8px')
    await input.fill('99')
    await page.locator('#shrink').click()
    await expect(input).toHaveValue('3')
    await page.locator('#disable').click()
    await expect(input).toBeDisabled()
    await expect(apply).toBeDisabled()
    await expect(page.locator('#steps button').first()).toBeDisabled()
    await page.locator('#disable').click()
    await page.locator('#empty').click()
    await expect(input).toBeDisabled()
    await expect(apply).toBeDisabled()
    await expect(pagination.locator('[aria-current="page"]')).toHaveText('1')
    expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBeLessThanOrEqual(width)
  })
}


test('narrow pagination preserves 44px square targets by reducing pages and keeps its indicator aligned', async ({page}) => {
  await page.setViewportSize({width:320,height:900})
  await page.goto('/components#apple-pagination')
  const demo = page.locator('#apple-pagination .component-demo')
  const pagination = demo.locator('.apple-pagination')
  const track = pagination.locator('.apple-pagination__pages')
  const input = pagination.getByRole('textbox',{name:'跳转页码'})
  for (const pageNumber of [1,2,6,12,3]) {
    await input.fill(String(pageNumber))
    await input.press('Enter')
    await expect(track.locator('[aria-current="page"]')).toHaveText(String(pageNumber))
    await expect.poll(() => track.evaluate(el => el.scrollWidth <= el.clientWidth + 1)).toBe(true)
    const bounds = await demo.boundingBox()
    for (const button of await track.locator(':scope > button').all()) {
      const rect = (await button.boundingBox())!
      expect(rect.width).toBeCloseTo(44,3)
      expect(rect.height).toBeCloseTo(44,3)
      expect(rect.x).toBeGreaterThanOrEqual(bounds!.x)
      expect(rect.x + rect.width).toBeLessThanOrEqual(bounds!.x + bounds!.width + .1)
    }
    await expect.poll(() => track.locator('.apple-pagination__indicator').evaluate(el => {
      const a=el.getBoundingClientRect(), b=el.parentElement!.querySelector('[aria-current="page"]')!.getBoundingClientRect()
      return Math.abs(a.x-b.x)+Math.abs(a.width-b.width)
    })).toBeLessThan(1)
  }
  expect(await page.evaluate(()=>document.documentElement.scrollWidth)).toBeLessThanOrEqual(320)
})

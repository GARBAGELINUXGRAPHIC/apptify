import { readFile, writeFile } from 'node:fs/promises'
import { fileURLToPath } from 'node:url'
import ts from 'typescript'
import postcss from 'postcss'

// Extract the actual AppleInput declarations with TypeScript's AST. Preserve
// implementation logic; only erase TS types and route dependencies to public ESM.
export async function prepareInputSource() {
  const root = new URL('../', import.meta.url)
  const source = await readFile(new URL('src/components/forms.ts', root), 'utf8')
  const ast = ts.createSourceFile('forms.ts', source, ts.ScriptTarget.Latest, true, ts.ScriptKind.TS)
  const names = ['fieldProps', 'FieldVm', 'fieldId', 'controlAttrs', 'field', 'spinner', 'stringValue', 'AppleInput']
  const declarations = new Map()
  for (const statement of ast.statements) {
    const name = ts.isVariableStatement(statement) ? statement.declarationList.declarations[0]?.name.getText(ast) : statement.name?.getText(ast)
    if (names.includes(name)) declarations.set(name, statement.getText(ast))
  }
  for (const name of names) if (!declarations.has(name)) throw new Error(`AppleInput source changed: missing ${name}`)
  const script = [
    "import { defineComponent, h, useId, type PropType, type Slots, type VNodeChild } from 'vue'",
    "import { ripple } from 'apptify'",
    "import { Eye, EyeOff, LoaderCircle, X } from 'lucide-vue-next'",
    ...names.map(name => declarations.get(name)),
    'export default AppleInput',
  ].join('\n\n')
  const js = ts.transpileModule(script, { compilerOptions: { target: ts.ScriptTarget.ES2022, module: ts.ModuleKind.ESNext } }).outputText
  const cssAst = postcss.parse(await readFile(new URL('src/styles/forms.css', root), 'utf8'))
  const boundary = cssAst.nodes.findIndex(node => node.type === 'rule' && node.selector === '.apple-textarea')
  if (boundary < 0) throw new Error('Input CSS section changed: review source extraction')
  const css = cssAst.nodes.slice(0, boundary).map(node => node.toString()).join('\n')
  const code = `<!-- AppleInput 同源实现：src/components/forms.ts + src/styles/forms.css。\n只移除 TypeScript 类型并转接浏览器公开依赖，保留 Options API/render 实现。 -->\n<script>\n${js}</script>\n\n<style>\n${css}\n</style>\n`
  const destination = new URL('playground/editor/apple-input-source.ts', root)
  const snapshot = '// Generated by tooling/prepare-input-source.mjs; do not edit the snapshot by hand.\nexport default ' + JSON.stringify(code) + '\n'
  // Do not trigger a hot update during dev-server startup for unchanged data.
  const previous = await readFile(destination, 'utf8').catch(() => undefined)
  if (previous !== snapshot) await writeFile(destination, snapshot)
}
if (process.argv[1] === fileURLToPath(import.meta.url)) await prepareInputSource()
